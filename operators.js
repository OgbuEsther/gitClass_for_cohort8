//arithmetic operators
let x = 50
let y = 5
console.log(x + y)
console.log(x - y)
console.log(x * y)
console.log(x / y)
console.log(x % y)

//comparison operators
let a = 10;
let b = 20;
console.log(a === b);
console.log(a !== b);
console.log(a < b);
console.log(a > b);
console.log(a <= b);
console.log(a >= b);

const isFemale = false
console.log(!isFemale)

//logical operators
let isAdult = true;
let hasID = false;
console.log(isAdult && hasID);
console.log(isAdult || hasID);
console.log(!isAdult);


//assignment operators
let t = 20
console.log(t)
console.log(t += 5)
console.log(t -= 10)
console.log(t *= 2)
console.log(t /= 2)
console.log(t %= 2)
